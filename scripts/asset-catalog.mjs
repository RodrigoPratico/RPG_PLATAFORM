/** Discover regional scenes using the repository's existing Portuguese file layout. */
import {readdir,readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve,relative,dirname,extname,basename} from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {syncAssetPaths,validateAssetLayout} from './asset-paths.mjs';

export const assetKey=value=>value.normalize('NFD').replace(/\p{M}/gu,'').toLocaleLowerCase('pt-BR').replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
export async function discoverScenes(dist,config) {
 const directory=resolve(dist,'assets/Mapa/Regiões');const groups=await readdir(directory,{withFileTypes:true}).catch(err=>{if(err.code==='ENOENT')return [];throw err;});
 const entries=[],warnings=[];
 for(const group of groups.filter(d=>d.isDirectory()&&/-Subregioes$/i.test(d.name)).sort((a,b)=>a.name.localeCompare(b.name,'pt-BR'))){
  const regionName=group.name.replace(/-Subregioes$/i,''),parentKey=assetKey(regionName),parentRegionId=config.parents[parentKey]||'';
  const variants=new Map();
  for(const file of await readdir(resolve(directory,group.name),{withFileTypes:true})){
   if(!file.isFile()||!['.png','.jpg','.jpeg','.webp'].includes(extname(file.name).toLowerCase()))continue;
   const stem=basename(file.name,extname(file.name)),parts=stem.split(' - ');
   if(parts.length<2||assetKey(parts[0])!==parentKey)throw new Error('Nome fora do padrão <Região> - <Local>: '+group.name+'/'+file.name);
   const key=assetKey(stem);if(key.length>85)throw new Error('Nome de local muito longo: '+stem);
   const record=variants.get(key)||{key,name:parts.slice(1).join(' - '),group:regionName,parentRegionId,variants:[]};
   record.variants.push({name:file.name,extension:extname(file.name).toLowerCase()});variants.set(key,record);
  }
  for(const record of variants.values()){
   record.variants.sort((a,b)=>a.name.localeCompare(b.name,'pt-BR'));
   const best=record.variants.find(v=>v.extension==='.webp')||record.variants.find(v=>v.extension==='.png')||record.variants[0];
   const original=record.variants.find(v=>v.extension==='.png')||best;
   const image='assets/Mapa/Regiões/'+group.name+'/'+best.name,source='assets/Mapa/Regiões/'+group.name+'/'+original.name;
   const placement=config.placements[record.key]||{};
   const sha=createHash('sha256').update(await readFile(resolve(dist,image))).digest('hex');
   entries.push({key:record.key,name:record.name,group:record.group,parentRegionId,image,source,sha,...placement});
   if(!parentRegionId)warnings.push('Associe a pasta '+group.name+' a uma região em assets.config.json.');
  }
 }
 entries.sort((a,b)=>a.key.localeCompare(b.key));
 const revision=createHash('sha256').update(JSON.stringify(entries)).digest('hex').slice(0,20);
 return {version:1,revision,entries,warnings:[...new Set(warnings)]};
}
export async function buildAssetCatalog(root) {
 const config=JSON.parse(await readFile(resolve(root,'assets.config.json'),'utf8'));
 const catalog=await discoverScenes(resolve(root,'dist'),config),target=resolve(root,'dist/features/atlas/data/catalog.generated.js');
 await mkdir(dirname(target),{recursive:true});await writeFile(target,'// Generated by scripts/asset-catalog.mjs. Preserve asset paths, case and accents.\nexport const sceneCatalog = '+JSON.stringify(catalog,null,2)+';\n');
 return catalog;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
 await syncAssetPaths(root);await validateAssetLayout(resolve(root,'dist'));
 const catalog=await buildAssetCatalog(root);
 console.log(JSON.stringify({event:'asset_catalog',scenes:catalog.entries.length,warnings:catalog.warnings}));
}
